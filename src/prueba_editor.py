"""Prueba del editor modal sin servidor de audio. Uso: .venv/bin/python -I src/prueba_editor.py [captura.svg]"""
import asyncio, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import editor, tempfile
from editor import Editor, Codigo
editor.ARCHIVO_TEMA = os.path.join(tempfile.mkdtemp(), "tema.json")   # nunca tocar la configuracion real

def check(nombre, ok):
    print(("OK    " if ok else "FALLA ") + nombre); return ok

async def main():
    app = Editor(con_servidor=False); todo = []
    async with app.run_test(size=(110, 34)) as pilot:
        cod = app.query_one("#cod", Codigo)
        async def reset(texto):
            app._poner(texto); await pilot.pause()
        async def t(*k): await pilot.press(*k); await pilot.pause()
        todo.append(check("arranca en modo normal y de solo lectura", cod.modo == "normal" and cod.read_only))
        await reset("uno dos\ntres\ncuatro")
        await t("x", "y", "z")
        todo.append(check("en normal las letras NO escriben", cod.text == "no dos\ntres\ncuatro" or cod.text.startswith("no dos")))
        await reset("uno dos\ntres\ncuatro")
        await t("w", "i", "X", "escape")
        todo.append(check("w + i + texto + Esc", cod.text.startswith("uno Xdos") and cod.modo == "normal"))
        await reset("a\nb\nc")
        await t("j", "d", "d")
        todo.append(check("dd", cod.text == "a\nc"))
        await t("p")
        todo.append(check("p pega la linea", cod.text == "a\nc\nb" and cod.cursor_location[0] == 2))
        await t("u")
        todo.append(check("u deshace", cod.text == "a\nc"))
        await t("U")
        todo.append(check("U rehace", cod.text == "a\nc\nb"))
        await reset("a\nb\nc")
        await t("y", "y", "G", "p")
        todo.append(check("yy G p", cod.text == "a\nb\nc\na"))
        await reset("live_loop :x do")
        await t("A", "enter", "p", "escape")
        todo.append(check("sangria tras do", cod.text == "live_loop :x do\n  p"))
        await reset("uno dos tres")
        await t("d", "w")
        todo.append(check("dw", cod.text == "dos tres"))
        await t("2", "x")
        todo.append(check("2x", cod.text == "s tres"))
        await t("c", "w", "H", "escape")
        todo.append(check("cw", cod.text == "H tres"))
        await reset("a\nb\nc\nd")
        await t("3", "j")
        todo.append(check("3j", cod.cursor_location[0] == 3))
        await t("g", "g")
        todo.append(check("gg", cod.cursor_location[0] == 0))
        await t("o", "n", "escape")
        todo.append(check("o abre linea debajo", cod.text == "a\nn\nb\nc\nd"))
        await reset("uno dos tres")
        await t("v", "l", "l", "l", "y")
        todo.append(check("visual + y", cod.reg[0] == "uno" and cod.modo == "normal"))
        await t("v", "w", "d")
        todo.append(check("visual + d", cod.text == "dos tres" or cod.text.startswith("dos") or "uno" not in cod.text))
        # lider
        await t("space")
        todo.append(check("Espacio abre el menu", cod.lider is not None and "ejecutar" in str(app.query_one('#ayuda').render())))
        await t("f")
        todo.append(check("Espacio f abre submenu", cod.ruta_lider.strip() == "f"))
        await t("escape")
        todo.append(check("Esc cierra el menu", cod.lider is None))
        todo.append(check("log oculto y ayuda oculta por defecto", not app.query_one("#log").display and not app.query_one("#ayuda").display))
        await t("space", "o", "l")
        todo.append(check("Espacio o l muestra el log", app.query_one("#log").display and app.log_visible))
        await t("space", "o", "l")
        todo.append(check("Espacio o l lo oculta", not app.query_one("#log").display))
        app._log("fallo de prueba", "red")
        await pilot.pause()
        todo.append(check("un error abre el log", app.query_one("#log").display))
        await t("space", "o", "l")
        app._log("hola barra", "ok"); await pilot.pause()
        todo.append(check("ultimo mensaje en la barra con el log oculto", "hola barra" in str(app.query_one("#barra").render())))
        await t("space")
        todo.append(check("la ayuda aparece solo con Espacio", app.query_one("#ayuda").display))
        await t("escape")
        todo.append(check("y se oculta al cerrar", not app.query_one("#ayuda").display))
        # ctrl+q no cierra
        await t("ctrl+q")
        todo.append(check("Ctrl+Q ya no cierra el editor", app.is_running))
        # salir con cambios pide confirmar
        app.sucio = True
        await t("space", "q")
        todo.append(check("Espacio q con cambios pide confirmar", app.is_running and app._confirma_salir))
        # paleta
        await t("space", "p")
        todo.append(check("Espacio p abre la paleta", app.screen.__class__.__name__ == "Selector"))
        await t("escape")
        todo.append(check("Esc cierra la paleta", app.screen.__class__.__name__ != "Selector"))
        await t("space", "v", "u")
        todo.append(check("Espacio v u sube el volumen", abs(app.volumen - 0.35) < 1e-9))
        await t("i")
        todo.append(check("insertar escribe", cod.modo == "insertar" and not cod.read_only))
        await t("h", "o", "l", "a")
        todo.append(check("texto en insertar", "hola" in cod.text))
        await t("escape")
        if len(sys.argv) > 1: open(sys.argv[1], "w").write(app.export_screenshot())
    print(f"\n{sum(todo)}/{len(todo)} comprobaciones correctas")
asyncio.run(main())
